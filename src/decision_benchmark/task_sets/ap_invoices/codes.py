"""Decisions, priority tiers, every finding and reason code (one StrEnum) and the priority table.

ORDER is the spec's priority (fraud, duplicate, invalid invoice, mismatch,
routing) with a fixed order inside each tier (step-11 plan §5.2, Q7). Each
finding code sets one decision. The reason-only codes (CLEAN, DISALLOWED,
HANDOVER) never come from a finding.
"""

from __future__ import annotations

from enum import IntEnum, StrEnum


class Decision(StrEnum):
    APPROVE = "APPROVE"
    DISPUTE_PRICE = "DISPUTE_PRICE"
    DISPUTE_QUANTITY = "DISPUTE_QUANTITY"
    HOLD_NOT_RECEIVED = "HOLD_NOT_RECEIVED"
    REJECT_DUPLICATE = "REJECT_DUPLICATE"
    REQUEST_CORRECTED_INVOICE = "REQUEST_CORRECTED_INVOICE"
    FRAUD_REVIEW = "FRAUD_REVIEW"
    ROUTE_FOR_APPROVAL = "ROUTE_FOR_APPROVAL"
    HAND_OVER = "HAND_OVER"


class Tier(IntEnum):
    """Decision priority from the spec: fraud, duplicate, invalid invoice, mismatch, routing."""

    FRAUD = 1
    DUPLICATE = 2
    INVALID_INVOICE = 3
    MISMATCH = 4
    ROUTING = 5


class Code(StrEnum):
    # Findings, in priority order
    BANK_DETAILS_DIFFER_FROM_RECORD = "BANK_DETAILS_DIFFER_FROM_RECORD"
    BANK_CHANGE_BY_EMAIL_ONLY = "BANK_CHANGE_BY_EMAIL_ONLY"
    DUPLICATE_INVOICE = "DUPLICATE_INVOICE"
    NEAR_DUPLICATE = "NEAR_DUPLICATE"
    MISSING_MANDATORY_FIELD = "MISSING_MANDATORY_FIELD"
    INVALID_TAX_INVOICE = "INVALID_TAX_INVOICE"
    FOREIGN_CURRENCY_NO_SGD_AMOUNTS = "FOREIGN_CURRENCY_NO_SGD_AMOUNTS"
    SUPPLIER_NOT_TAX_REGISTERED = "SUPPLIER_NOT_TAX_REGISTERED"
    OVR_GST_CHARGED_TO_REGISTERED_BUYER = "OVR_GST_CHARGED_TO_REGISTERED_BUYER"
    TAX_SHOULD_BE_EXEMPT = "TAX_SHOULD_BE_EXEMPT"
    WRONG_TAX_RATE = "WRONG_TAX_RATE"
    NOT_RECEIVED = "NOT_RECEIVED"
    QUANTITY_ABOVE_RECEIVED = "QUANTITY_ABOVE_RECEIVED"
    PRICE_ABOVE_PO = "PRICE_ABOVE_PO"
    NO_PO = "NO_PO"
    ABOVE_APPROVAL_LIMIT = "ABOVE_APPROVAL_LIMIT"
    # Reasons that are not findings
    MATCHED_WITHIN_TOLERANCE = "MATCHED_WITHIN_TOLERANCE"
    GST_NOT_CLAIMABLE_DISALLOWED = "GST_NOT_CLAIMABLE_DISALLOWED"
    CANNOT_SETTLE_FROM_RULES = "CANNOT_SETTLE_FROM_RULES"


ORDER: tuple[tuple[Code, Tier, Decision], ...] = (
    (Code.BANK_DETAILS_DIFFER_FROM_RECORD, Tier.FRAUD, Decision.FRAUD_REVIEW),
    (Code.BANK_CHANGE_BY_EMAIL_ONLY, Tier.FRAUD, Decision.FRAUD_REVIEW),
    (Code.DUPLICATE_INVOICE, Tier.DUPLICATE, Decision.REJECT_DUPLICATE),
    (Code.NEAR_DUPLICATE, Tier.DUPLICATE, Decision.REJECT_DUPLICATE),
    (Code.MISSING_MANDATORY_FIELD, Tier.INVALID_INVOICE, Decision.REQUEST_CORRECTED_INVOICE),
    (Code.INVALID_TAX_INVOICE, Tier.INVALID_INVOICE, Decision.REQUEST_CORRECTED_INVOICE),
    (Code.FOREIGN_CURRENCY_NO_SGD_AMOUNTS, Tier.INVALID_INVOICE, Decision.REQUEST_CORRECTED_INVOICE),
    (Code.SUPPLIER_NOT_TAX_REGISTERED, Tier.INVALID_INVOICE, Decision.REQUEST_CORRECTED_INVOICE),
    (Code.OVR_GST_CHARGED_TO_REGISTERED_BUYER, Tier.INVALID_INVOICE, Decision.REQUEST_CORRECTED_INVOICE),
    (Code.TAX_SHOULD_BE_EXEMPT, Tier.INVALID_INVOICE, Decision.REQUEST_CORRECTED_INVOICE),
    (Code.WRONG_TAX_RATE, Tier.INVALID_INVOICE, Decision.REQUEST_CORRECTED_INVOICE),
    (Code.NOT_RECEIVED, Tier.MISMATCH, Decision.HOLD_NOT_RECEIVED),
    (Code.QUANTITY_ABOVE_RECEIVED, Tier.MISMATCH, Decision.DISPUTE_QUANTITY),
    (Code.PRICE_ABOVE_PO, Tier.MISMATCH, Decision.DISPUTE_PRICE),
    (Code.NO_PO, Tier.ROUTING, Decision.ROUTE_FOR_APPROVAL),
    (Code.ABOVE_APPROVAL_LIMIT, Tier.ROUTING, Decision.ROUTE_FOR_APPROVAL),
)

REASON_ONLY = frozenset({Code.MATCHED_WITHIN_TOLERANCE, Code.GST_NOT_CLAIMABLE_DISALLOWED, Code.CANNOT_SETTLE_FROM_RULES})
